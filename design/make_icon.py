#!/usr/bin/env python3
"""Generate Orb's icon assets from one geometry, in the GrapheneOS app-icon style.

Writes:
  overlay/util/src/androidMain/res/drawable/orb_launcher_foreground.xml  (launcher, colour highlight)
  overlay/util/src/androidMain/res/drawable/orb_launcher_monochrome.xml  (themed icon, cut-out)
  overlay/util/src/androidMain/res/values/ic_launcher_background.xml     (white)
  overlay/util/src/androidMain/res/drawable/ic_notification.xml          (status bar)
  design/orb-icon.svg                                                    (master, 108 canvas)
  fastlane/metadata/android/en-US/images/icon.png                        (512x512 store icon)
Run from anywhere: python3 design/make_icon.py
"""
import math
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "overlay/util/src/androidMain/res"

# Geometry in the 108x108 adaptive-icon canvas (the launcher shows the middle 72x72).
CX = CY = 54.0
R_ORB = 22.0                       # the sphere
HL_A0, HL_A1 = 196.0, 254.0        # highlight arc, degrees, y pointing down
HL_OUT, HL_IN = 17.5, 12.5         # highlight band radii (cut out of the sphere)
INK, PAPER = "#000000", "#FFFFFF"  # GrapheneOS apps: black glyph on white
HL_FROM, HL_TO = "#00D8FF", "#FF4FC8"  # highlight gradient, cyan to pink, along the arc


def pt(a, r, s, ox, oy):
    return (ox + s * (CX + r * math.cos(math.radians(a)) - CX),
            oy + s * (CY + r * math.sin(math.radians(a)) - CY))


def fmt(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def sphere(s=1.0, ox=CX, oy=CY):
    r = R_ORB * s
    return f"M{fmt(ox - r)},{fmt(oy)} a{fmt(r)},{fmt(r)} 0 1,0 {fmt(2 * r)},0 a{fmt(r)},{fmt(r)} 0 1,0 {fmt(-2 * r)},0 Z"


def band(s=1.0, ox=CX, oy=CY):
    o, i, cap = HL_OUT * s, HL_IN * s, (HL_OUT - HL_IN) / 2 * s
    f = fmt
    x1, y1 = pt(HL_A0, HL_OUT, s, ox, oy); x2, y2 = pt(HL_A1, HL_OUT, s, ox, oy)
    x3, y3 = pt(HL_A1, HL_IN, s, ox, oy); x4, y4 = pt(HL_A0, HL_IN, s, ox, oy)
    return (f"M{f(x1)},{f(y1)} A{f(o)},{f(o)} 0 0,1 {f(x2)},{f(y2)} "
            f"A{f(cap)},{f(cap)} 0 0,1 {f(x3)},{f(y3)} A{f(i)},{f(i)} 0 0,0 {f(x4)},{f(y4)} "
            f"A{f(cap)},{f(cap)} 0 0,1 {f(x1)},{f(y1)} Z")


def gradient_ends():
    """Start and end of the highlight gradient: the band's two ends, on its centre line."""
    mid = (HL_OUT + HL_IN) / 2
    return pt(HL_A0, mid, 1, CX, CY), pt(HL_A1, mid, 1, CX, CY)


def glyph(s=1.0, ox=CX, oy=CY):
    """Path data for the orb with its highlight cut out (even-odd), scaled by s about centre
    and moved to (ox, oy)."""
    return f"{sphere(s, ox, oy)} {band(s, ox, oy)}"


def vector(w, h, vw, vh, d, color, comment):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by design/make_icon.py; edit that, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{w}dp"
    android:height="{h}dp"
    android:viewportWidth="{vw}"
    android:viewportHeight="{vh}">
    <path
        android:fillColor="{color}"
        android:fillType="evenOdd"
        android:pathData="{d}" />
</vector>
"""


def foreground():
    (x0, y0), (x1, y1) = gradient_ends()
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Orb launcher glyph: a black sphere with a cyan-to-pink highlight. The themed icon uses
     orb_launcher_monochrome. Generated by design/make_icon.py; edit that, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="{INK}"
        android:pathData="{sphere()}" />
    <path android:pathData="{band()}">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="{fmt(x0)}"
                android:startY="{fmt(y0)}"
                android:endX="{fmt(x1)}"
                android:endY="{fmt(y1)}"
                android:startColor="{HL_FROM}"
                android:endColor="{HL_TO}" />
        </aapt:attr>
    </path>
</vector>
"""


def main():
    (RES / "drawable/orb_launcher_foreground.xml").write_text(foreground())
    (RES / "drawable/orb_launcher_monochrome.xml").write_text(vector(
        108, 108, 108, 108, glyph(), INK,
        "Orb themed-icon layer: the sphere with its highlight cut out."))
    (RES / "values/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{PAPER}</color>\n</resources>\n')
    # Status bar: 24dp, glyph ~18dp wide (Material notification icon keyline), white.
    (RES / "drawable/ic_notification.xml").write_text(vector(
        24, 24, 24, 24, glyph(s=9.5 / R_ORB, ox=12, oy=12), "#FFFFFFFF",
        "Orb status-bar mark."))
    (x0, y0), (x1, y1) = gradient_ends()
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">'
           f'<defs><linearGradient id="hl" gradientUnits="userSpaceOnUse" x1="{fmt(x0)}" '
           f'y1="{fmt(y0)}" x2="{fmt(x1)}" y2="{fmt(y1)}"><stop offset="0" stop-color="{HL_FROM}"/>'
           f'<stop offset="1" stop-color="{HL_TO}"/></linearGradient></defs>'
           f'<rect width="108" height="108" fill="{PAPER}"/>'
           f'<path d="{sphere()}" fill="{INK}"/><path d="{band()}" fill="url(#hl)"/></svg>\n')
    (ROOT / "design/orb-icon.svg").write_text(svg)
    # Store icon: the 72x72 area a launcher shows, full-bleed square (stores apply the mask).
    store = svg.replace('viewBox="0 0 108 108" width="108" height="108"',
                        'viewBox="18 18 72 72" width="512" height="512"')
    png = ROOT / "fastlane/metadata/android/en-US/images/icon.png"
    subprocess.run(["magick", "-background", "none", "-density", "300", "svg:-",
                    "-resize", "512x512", "-strip", "-define", "png:exclude-chunks=date,time",
                    f"PNG24:{png}"], input=store.encode(), check=True)


main()
